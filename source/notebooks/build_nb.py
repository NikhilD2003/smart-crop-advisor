"""Joins the numbered scripts into one notebook (no jupytext needed), shows every graph inline, runs it, saves it.
Run: python source/notebooks/build_nb.py   (needs internet only for part 03's cross-dataset download; it is skipped offline)"""
import re
from pathlib import Path
import nbformat as nbf
from nbclient import NotebookClient

HERE = Path(__file__).parent
INTRO = """# Smart Crop Advisor (PAI101)
Run top to bottom (Kernel -> Restart & Run All). Every graph is drawn inline and also saved to `source/models/figures/`.

| Part | Script | What it does | Main outputs |
|---|---|---|---|
| 1 | `01_prepare.py` | Clean both datasets, descriptive + exploratory + inferential analysis | `data/processed/*_clean.csv`, `eda.json` |
| 1b | `01b_synthetic.py` | Generate the **synthetic crop dataset** of weak and poor fields (needed because public data has only good fields) | `data/processed/synthetic_crop_dataset.csv`, `crop_profile.json` |
| 2 | `02_train.py` | Train + compare tree / forest / neural network, SHAP, K-means zones, yield regression, Edge AI numbers, label poisoning, suitability model, export to the browser | `metrics.json`, `*.joblib`, `frontend/data/model.json` |
| 3 | `03_analysis.py` | **Statistical analysis**, **ablation study**, **cross-dataset validation** | `analysis.json`, `stat_*.png`, `ablation_*.png`, `cross_dataset.png` |

**Key idea.** The public dataset contains only *good* fields for each crop, so a classifier alone cannot say "this field is bad for
rice". The synthetic dataset adds poor and marginal fields (clearly labelled as generated by us), and the suitability model learns
from both, giving a 0-100% score per crop that falls for poor fits and rises as the readings improve.
"""

nb = nbf.v4.new_notebook()
nb.cells.append(nbf.v4.new_markdown_cell(INTRO))
for f in ("01_prepare.py", "01b_synthetic.py", "02_train.py", "03_analysis.py"):
    src = (HERE / f).read_text(encoding="utf-8").replace(
        "Path(__file__).resolve().parents[2]", "Path.cwd().resolve().parents[1] if Path.cwd().name == 'notebooks' else Path.cwd()")
    src = src.replace('matplotlib.use("Agg")', "pass  # inline backend in the notebook").replace("plt.close()", "plt.show()")
    for chunk in re.split(r"(?m)^# %%", src):
        if not chunk.strip():
            continue
        if chunk.startswith(" [markdown]"):
            body = "\n".join(l[2:] if l.startswith("# ") else l.lstrip("#") for l in chunk.split("\n", 1)[1].splitlines())
            nb.cells.append(nbf.v4.new_markdown_cell(body))
        else:
            nb.cells.append(nbf.v4.new_code_cell(chunk.strip("\n")))
NotebookClient(nb, timeout=1800, resources={"metadata": {"path": str(HERE)}}).execute()
nbf.write(nb, HERE / "smart_crop_advisor.ipynb")
print("cells:", len(nb.cells))
